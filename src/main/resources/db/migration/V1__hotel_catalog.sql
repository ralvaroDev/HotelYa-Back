CREATE TABLE hotel (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE,
 name varchar(200) NOT NULL,
 description text NOT NULL,
 address varchar(500) NOT NULL,
 location varchar(200) NOT NULL,
 phone varchar(40),
 logo_path varchar(500),
 facade_path varchar(500),
 video_path varchar(500),
 latitude numeric(9,6) CHECK (latitude BETWEEN -90 AND 90),
 longitude numeric(9,6) CHECK (longitude BETWEEN -180 AND 180),
 whatsapp varchar(40),
 opening_hours text,
 check_in_out_conditions text,
 has_parking boolean
);
CREATE TABLE room_type (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hotel_id bigint NOT NULL REFERENCES hotel(id),
 code varchar(80) NOT NULL,
 name varchar(200) NOT NULL,
 description text NOT NULL,
 display_order integer NOT NULL CHECK (display_order >= 0),
 UNIQUE (hotel_id, code)
);
CREATE TABLE room_photo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_type_id bigint NOT NULL REFERENCES room_type(id),
 path varchar(500) NOT NULL,
 alt_text varchar(300) NOT NULL,
 display_order integer NOT NULL CHECK (display_order >= 0)
);
CREATE TABLE room_detail (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_type_id bigint NOT NULL REFERENCES room_type(id),
 kind varchar(40) NOT NULL CHECK (kind IN ('FEATURE','SERVICE','RECOMMENDATION','PROHIBITION')),
 text text NOT NULL,
 display_order integer NOT NULL CHECK (display_order >= 0)
);
CREATE TABLE rate (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_type_id bigint NOT NULL REFERENCES room_type(id),
 mode varchar(20) NOT NULL CHECK (mode IN ('HOUR','PACKAGE','NIGHT')),
 amount numeric(12,2) NOT NULL CHECK (amount > 0),
 currency varchar(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
 package_hours integer,
 additional_hour_amount numeric(12,2),
 simulated boolean NOT NULL,
 CHECK ((mode = 'PACKAGE' AND package_hours > 0 AND package_hours IS NOT NULL
         AND additional_hour_amount >= 0 AND additional_hour_amount IS NOT NULL)
        OR (mode <> 'PACKAGE' AND package_hours IS NULL AND additional_hour_amount IS NULL))
);
CREATE INDEX room_type_hotel_idx ON room_type(hotel_id, display_order);
CREATE INDEX room_photo_type_idx ON room_photo(room_type_id, display_order);
CREATE INDEX room_detail_type_idx ON room_detail(room_type_id, display_order);
CREATE INDEX rate_type_idx ON rate(room_type_id);
-- Catalog data is accessible through Spring's JDBC connection, not Supabase's Data API.
REVOKE ALL ON SCHEMA "${catalogSchema}" FROM anon, authenticated, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA "${catalogSchema}" FROM anon, authenticated, service_role;
