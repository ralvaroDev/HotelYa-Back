CREATE TABLE owner_account (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL UNIQUE,
 password_hash varchar(100) NOT NULL,
 created_at timestamptz NOT NULL
);
CREATE TABLE owner_session (
 id uuid PRIMARY KEY,
 owner_id bigint NOT NULL REFERENCES owner_account(id),
 refresh_hash varchar(64) NOT NULL,
 expires_at timestamptz NOT NULL,
 revoked boolean NOT NULL DEFAULT false
);
CREATE INDEX owner_session_owner_idx ON owner_session(owner_id);
ALTER TABLE hotel ADD COLUMN owner_id bigint UNIQUE REFERENCES owner_account(id);
ALTER TABLE hotel ADD COLUMN published boolean NOT NULL DEFAULT true;
ALTER TABLE hotel ALTER COLUMN published SET DEFAULT false;
ALTER TABLE room_type ADD COLUMN total_units integer;
ALTER TABLE room_type ADD COLUMN available_units integer;
ALTER TABLE room_type ADD CONSTRAINT room_inventory_check CHECK (
 (total_units IS NULL AND available_units IS NULL) OR
 (total_units IS NOT NULL AND available_units IS NOT NULL AND total_units >= 0
  AND available_units >= 0 AND available_units <= total_units)
);
CREATE TABLE media_file (
 id uuid PRIMARY KEY,
 hotel_id bigint NOT NULL REFERENCES hotel(id),
 content_type varchar(50) NOT NULL,
 original_name varchar(255) NOT NULL,
 byte_size bigint NOT NULL CHECK (byte_size > 0)
);
CREATE INDEX media_file_hotel_idx ON media_file(hotel_id);
CREATE TABLE stay_card (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hotel_id bigint NOT NULL REFERENCES hotel(id),
 title varchar(200) NOT NULL,
 description text NOT NULL,
 display_order integer NOT NULL CHECK(display_order >= 0)
);
CREATE INDEX stay_card_hotel_idx ON stay_card(hotel_id, display_order);
